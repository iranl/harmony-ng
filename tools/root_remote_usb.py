#!/usr/bin/env python3
"""Logitech Harmony Elite Remote USB Root & Persistence Tool.

Supports 3 primary installation methods:
  - Method A (Hardware Recovery): Hold Menu+Mute 15s (or hold Off while plugging USB).
    Boots directly into USB RNDIS gadget mode (192.168.2.1) without touchscreen.
  - Method B (Keypad Debug Menu): >> + Stop + Red -> D-pad to "Enable USB Ethernet" -> OK.
    Enables RNDIS on stock running remote without touchscreen.
  - Method C (Direct USB HID Staging): Writes ARM Dropbear payload to /sys/dropbear,
    arms /tde/enable, and reboots without touching the remote.

Usage:
    python tools/root_remote_usb.py
    python tools/root_remote_usb.py --pubkey ~/.ssh/id_ed25519.pub
"""

from __future__ import annotations

import argparse
import hashlib
import os
import pathlib
import socket
import subprocess
import sys
import time

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
REPO_DIR = SCRIPT_DIR.parent
BIN_DIR = REPO_DIR / "elite" / "bin"
DROPBEAR_ARM_PATH = BIN_DIR / "dropbearmulti_musl"

if str(REPO_DIR) not in sys.path:
    sys.path.insert(0, str(REPO_DIR))

from tools.harmony_hid import HarmonyHid, ELITE_PID

REMOTE_IP = "192.168.2.1"
REMOTE_HTTP_PORT = 8088
REMOTE_SSH_PORT = 22

BOOTSTRAP_SCRIPT_TEMPLATE = b"""#!/bin/sh
# Auto-generated by Harmony Elite USB Root Tool
# Phase 1: Start USB Ethernet gadget
/usr/bin/usbeth start 2>/dev/null || true

# Phase 2: Install SSH authorized keys
mkdir -p /etc/dropbear /root/.ssh /home/root/.ssh
cat <<'EOF' > /etc/dropbear/authorized_keys
%PUBKEY%
EOF
cp /etc/dropbear/authorized_keys /root/.ssh/authorized_keys
cp /etc/dropbear/authorized_keys /home/root/.ssh/authorized_keys
chmod 700 /root /root/.ssh /home/root /home/root/.ssh
chmod 600 /etc/dropbear/authorized_keys /root/.ssh/authorized_keys /home/root/.ssh/authorized_keys

# Phase 3: Disable hardware watchdog
touch /etc/nowatchdog
chmod 644 /etc/nowatchdog

# Phase 4: Extract Dropbear multi-call binary using stock Lua
/usr/bin/lua -e 'local f=io.open("/usr/sbin/dropbearmulti","rb") f:seek("set",%OFFSET%) local g=io.open("/data/dropbearmulti","wb") while true do local b=f:read(65536) if not b then break end g:write(b) end f:close() g:close()'

chmod 755 /data/dropbearmulti
ln -sf /data/dropbearmulti /usr/sbin/dropbear
ln -sf /data/dropbearmulti /usr/sbin/dropbearkey
ln -sf /data/dropbearmulti /usr/sbin/dbclient
ln -sf /data/dropbearmulti /usr/sbin/scp

# Phase 5: Ensure RSA host key exists
if [ ! -r /etc/dropbear/dropbear_rsa_host_key ]; then
    /data/dropbearmulti dropbearkey -t rsa -f /etc/dropbear/dropbear_rsa_host_key
fi

# Phase 6: Ensure boot persistence in /etc/init.d/rcS.local
if [ ! -f /etc/init.d/rcS.local ]; then
    echo -e '#!/bin/sh\\n/usr/bin/usbeth start &\\n/data/dropbearmulti dropbear -R -p 0.0.0.0:22\\n' > /etc/init.d/rcS.local
    chmod 755 /etc/init.d/rcS.local
fi

# Phase 7: Start Dropbear SSH daemon
exec /data/dropbearmulti dropbear -R -p 0.0.0.0:22 "$@"
"""


def resolve_ssh_key(pubkey_path: str | None = None) -> tuple[pathlib.Path, str]:
    """Find existing harmony_owner key or generate a new ED25519 keypair."""
    ssh_dir = pathlib.Path.home() / ".ssh"
    ssh_dir.mkdir(parents=True, exist_ok=True)

    if pubkey_path:
        p = pathlib.Path(pubkey_path)
        if not p.is_file():
            raise FileNotFoundError(f"Specified pubkey not found: {pubkey_path}")
        return p, p.read_text(encoding="utf-8").strip()

    existing_keys = sorted(
        [k for k in ssh_dir.glob("harmony_owner_*.pub") if k.is_file()],
        key=lambda k: k.stat().st_mtime,
        reverse=True,
    )
    if existing_keys:
        chosen = existing_keys[0]
        print(f"[*] Using existing SSH key: {chosen}")
        return chosen, chosen.read_text(encoding="utf-8").strip()

    new_priv = ssh_dir / "harmony_owner_ed25519"
    new_pub = ssh_dir / "harmony_owner_ed25519.pub"
    print(f"[*] Generating new SSH keypair: {new_priv}...")
    cmd = ["ssh-keygen", "-t", "ed25519", "-f", str(new_priv), "-N", "", "-C", "harmony-elite-owner"]
    subprocess.run(cmd, check=True)
    return new_pub, new_pub.read_text(encoding="utf-8").strip()


def build_payload(pubkey_str: str) -> bytes:
    """Build self-extracting bootstrap script + ARM Dropbear binary."""
    if not DROPBEAR_ARM_PATH.is_file():
        raise FileNotFoundError(f"ARM Dropbear binary missing at {DROPBEAR_ARM_PATH}")

    arm_binary = DROPBEAR_ARM_PATH.read_bytes()
    dummy_offset = b"00000000"
    base_script = BOOTSTRAP_SCRIPT_TEMPLATE.replace(b"%PUBKEY%", pubkey_str.strip().encode("ascii"))
    template = base_script.replace(b"%OFFSET%", dummy_offset)
    actual_offset = len(template)

    final_offset_str = f"{actual_offset:08d}".encode("ascii")
    script = base_script.replace(b"%OFFSET%", final_offset_str)
    assert len(script) == actual_offset, f"Script length mismatch: {len(script)} vs {actual_offset}"

    return script + arm_binary


def probe_tcp(ip: str, port: int, timeout_s: float = 1.0) -> bool:
    """Check if TCP port is reachable."""
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    s.settimeout(timeout_s)
    try:
        s.connect((ip, port))
        s.close()
        return True
    except Exception:
        return False


def wait_for_ssh(ip: str = REMOTE_IP, port: int = REMOTE_SSH_PORT, timeout_s: int = 60) -> bool:
    """Poll SSH port until active."""
    t_end = time.time() + timeout_s
    while time.time() < t_end:
        if probe_tcp(ip, port, timeout_s=1.0):
            return True
        time.sleep(1.0)
        print(".", end="", flush=True)
    return False


def print_method_instructions() -> None:
    print("\n" + "=" * 70)
    print(" HARMONY ELITE SETUP OPTIONS (NO TOUCHSCREEN REQUIRED)")
    print("=" * 70)
    print(" [Method A] Hardware Recovery Mode (Recommended if screen is broken):")
    print("   1. Disconnect remote from USB and cradle.")
    print("   2. Hold 'Menu' + 'Mute' buttons for 15s (or hold 'Off' while plugging in USB).")
    print("   3. Remote screen displays USB gear icon -> boots into USB Ethernet gadget mode.")
    print("   4. Set PC IP to 192.168.2.2 (Gateway 192.168.2.1), then run setup_remote.py.")
    print()
    print(" [Method B] Keypad Debug Menu (If screen works but touch is dead):")
    print("   1. On running remote, press: >> (Fast Forward) + Stop + Red button.")
    print("   2. Use physical D-pad (Up/Down) to highlight 'Enable USB Ethernet'.")
    print("   3. Press Center/OK button to activate RNDIS interface.")
    print("   4. Set PC IP to 192.168.2.2, then run setup_remote.py.")
    print()
    print(" [Method C] Direct USB HID Staging (Attempting now over USB)...")
    print("=" * 70 + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Logitech Harmony Elite Remote USB Root & Persistence Tool")
    parser.add_argument("--pubkey", help="Path to SSH public key to authorize")
    parser.add_argument("--no-reboot", action="store_true", help="Do not reboot remote after staging Dropbear")
    args = parser.parse_args()

    print("=" * 70)
    print(" LOGITECH HARMONY ELITE REMOTE USB ROOT & PERSISTENCE TOOL")
    print("=" * 70)

    pub_path, pub_str = resolve_ssh_key(args.pubkey)
    print(f"[+] Authorized public key: {pub_str.split()[0]} {pub_str.split()[-1]}")

    # Check if remote is ALREADY in USB Ethernet mode (Method A or B)
    if probe_tcp(REMOTE_IP, REMOTE_SSH_PORT, timeout_s=0.5):
        print(f"[+] Remote is ALREADY online with SSH active at {REMOTE_IP}:{REMOTE_SSH_PORT}!")
        print("    Running deploy_elite.py to deploy Codex Elite runtime...")
        deploy_script = REPO_DIR / "elite" / "deploy_elite.py"
        subprocess.run([sys.executable, str(deploy_script), "--ip", REMOTE_IP, "--key", str(pub_path.with_suffix(""))])
        return

    if probe_tcp(REMOTE_IP, REMOTE_HTTP_PORT, timeout_s=0.5):
        print(f"[+] Remote is active in USB Ethernet mode (HTTP {REMOTE_IP}:{REMOTE_HTTP_PORT})!")
        print("    Running setup_remote.py --step 2 to install Dropbear and persistence...")
        setup_script = REPO_DIR / "elite" / "setup_remote.py"
        subprocess.run([sys.executable, str(setup_script), "--step", "2", "--key", str(pub_path.with_suffix(""))])
        return

    print_method_instructions()

    # Method C: Connect to Remote over USB HID
    print(f"[*] Searching for Harmony Elite Remote over USB HID (046D:C12B)...")
    hid = HarmonyHid(pid=ELITE_PID)
    if not hid.open():
        print("[-] Elite Remote not detected on USB HID (046D:C12B).")
        print("    Please connect remote via direct Micro-USB cable to PC.")
        print("    Alternatively, use Method A (Menu + Mute for 15s) to boot into RNDIS recovery.")
        sys.exit(1)

    try:
        payload = build_payload(pub_str)
        print(f"[+] Self-extracting ARM Dropbear payload built: {len(payload):,} bytes")

        print(f"[*] Staging Dropbear payload to /sys/dropbear ({len(payload):,} bytes)...")
        t0 = time.time()

        def progress(sent: int, total: int) -> None:
            pct = int(sent / total * 100)
            print(f"\r    Uploaded {sent:,} / {total:,} bytes ({pct}%)", end="", flush=True)

        hid.write_full_file("/sys/dropbear", payload, packets_per_chunk=5, progress_callback=progress)
        print(f"\n[+] Dropbear staging complete in {time.time() - t0:.1f}s.")

        print("[*] Arming boot trigger (/tde/enable -> /etc/tdeenable)...")
        if hid.set_tde_enable(True):
            print("[+] SUCCESS: /etc/tdeenable created.")
        else:
            print("[-] Warning: Failed to confirm /tde/enable.")

        if not args.no_reboot:
            print("[*] Sending reboot command to /sys/reboot...")
            hid.reboot()
            print("[+] Remote is rebooting into rooted firmware multi-user mode!")
            print(f"[*] Waiting for Dropbear SSH on {REMOTE_IP}:{REMOTE_SSH_PORT}...")
            if wait_for_ssh(REMOTE_IP, REMOTE_SSH_PORT, timeout_s=60):
                print(f"\n[+] SUCCESS: Dropbear SSH is ONLINE at {REMOTE_IP}:{REMOTE_SSH_PORT}!")
                print("    Deploying Codex Elite firmware...")
                deploy_script = REPO_DIR / "elite" / "deploy_elite.py"
                subprocess.run([sys.executable, str(deploy_script), "--ip", REMOTE_IP, "--key", str(pub_path.with_suffix(""))])
            else:
                print(f"\n[-] Timed out waiting for SSH on {REMOTE_IP}.")
                print("    If remote rebooted into HID mode, use Method A (Menu + Mute 15s) to launch RNDIS Ethernet.")
    finally:
        hid.close()


if __name__ == "__main__":
    main()
