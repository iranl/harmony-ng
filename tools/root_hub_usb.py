BOOTSTRAP_SCRIPT_TEMPLATE = b"""#!/bin/sh
# Auto-generated by Harmony Hub Control USB Root Tool
# Phase 1: Install SSH authorized keys
mkdir -p /etc/dropbear /root/.ssh /home/root/.ssh
cat <<'EOF' > /etc/dropbear/authorized_keys
%PUBKEY%
EOF
cp /etc/dropbear/authorized_keys /root/.ssh/authorized_keys
cp /etc/dropbear/authorized_keys /home/root/.ssh/authorized_keys
chmod 700 /root /root/.ssh /home/root /home/root/.ssh
chmod 600 /etc/dropbear/authorized_keys /root/.ssh/authorized_keys /home/root/.ssh/authorized_keys

# Phase 2: Set blank root password fallback in /etc/passwd
sed -i 's/^root:[^:]*:/root::/' /etc/passwd

# Phase 3: Disable hardware watchdog
touch /etc/nowatchdog
chmod 644 /etc/nowatchdog

# Phase 4: Extract Dropbear multi-call binary using stock Lua
/usr/bin/lua -e 'local f=io.open("/usr/sbin/dropbearmulti","rb") f:seek("set",%OFFSET%) local g=io.open("/data/dropbearmulti","wb") while true do local b=f:read(65536) if not b then break end g:write(b) end f:close() g:close()'

chmod 755 /data/dropbearmulti
ln -sf /data/dropbearmulti /usr/sbin/dropbear
ln -sf /data/dropbearmulti /usr/sbin/dropbearkey
ln -sf /data/dropbearmulti /usr/sbin/dbclient
ln -sf /data/dropbearmulti /usr/sbin/scp

# Phase 5: Ensure RSA host key exists
if [ ! -r /etc/dropbear/dropbear_rsa_host_key ]; then
    /data/dropbearmulti dropbearkey -t rsa -f /etc/dropbear/dropbear_rsa_host_key
fi

# Phase 6: Start Dropbear SSH daemon in background and let rcS continue
/data/dropbearmulti dropbear -R -p 0.0.0.0:22 "$@"
exit 0
"""


def resolve_ssh_key(pubkey_path: str | None = None) -> tuple[pathlib.Path, str]:
    """Find existing harmony_owner key or generate a new ED25519 keypair."""
    ssh_dir = pathlib.Path.home() / ".ssh"
    ssh_dir.mkdir(parents=True, exist_ok=True)

    if pubkey_path:
        p = pathlib.Path(pubkey_path)
        if not p.is_file():
            raise FileNotFoundError(f"Specified pubkey not found: {pubkey_path}")
        return p, p.read_text(encoding="utf-8").strip()

    # Look for existing harmony_owner keys
    existing_keys = sorted(
        [k for k in ssh_dir.glob("harmony_owner_*.pub") if k.is_file()],
        key=lambda k: k.stat().st_mtime,
        reverse=True,
    )
    if existing_keys:
        chosen = existing_keys[0]
        print(f"[*] Using existing SSH key: {chosen}")
        return chosen, chosen.read_text(encoding="utf-8").strip()

    # Generate new ED25519 key
    new_priv = ssh_dir / "harmony_owner_ed25519"
    new_pub = ssh_dir / "harmony_owner_ed25519.pub"
    print(f"[*] Generating new SSH keypair: {new_priv}...")
    cmd = ["ssh-keygen", "-t", "ed25519", "-f", str(new_priv), "-N", "", "-C", "harmony-hub-owner"]
    subprocess.run(cmd, check=True)
    return new_pub, new_pub.read_text(encoding="utf-8").strip()


def find_dropbear_binary() -> pathlib.Path:
    candidates = [
        SCRIPT_DIR / "bin" / "dropbearmulti_mips",
        SCRIPT_DIR / "bin" / "dropbearmulti",
        REPO_DIR / "bin" / "dropbearmulti",
        REPO_DIR / "bin" / "dropbearmulti_mips",
        REPO_DIR / "payload" / "bin" / "dropbearmulti",
        REPO_DIR / "payload" / "bin" / "dropbearmulti_mips",
        SCRIPT_DIR / "dropbearmulti_mips",
        SCRIPT_DIR / "dropbearmulti",
    ]
    for c in candidates:
        if c.is_file():
            return c
    raise FileNotFoundError(f"MIPS Dropbear binary missing. Checked: {[str(c) for c in candidates]}")


def build_payload(pubkey_str: str) -> bytes:
    """Build self-extracting bootstrap script + MIPS Dropbear binary."""
    dropbear_path = find_dropbear_binary()
    mips_binary = dropbear_path.read_bytes()

    dummy_offset = b"00000000"
    base_script = BOOTSTRAP_SCRIPT_TEMPLATE.replace(b"%PUBKEY%", pubkey_str.strip().encode("ascii"))
    template = base_script.replace(b"%OFFSET%", dummy_offset)
    actual_offset = len(template)

    final_offset_str = f"{actual_offset:08d}".encode("ascii")
    script = base_script.replace(b"%OFFSET%", final_offset_str)
    assert len(script) == actual_offset, f"Script length mismatch: {len(script)} vs {actual_offset}"

    return script + mips_binary


def check_tcp_port(ip: str, port: int, timeout_s: float = 1.0) -> bool:
    """Check if a TCP port is open."""
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.settimeout(timeout_s)
        res = s.connect_ex((ip, port))
        s.close()
        return res == 0
    except Exception:
        return False


def get_local_subnets() -> list[str]:
    """Discover local IPv4 /24 subnet prefixes (e.g. ['192.168.1'])."""
    subnets: set[str] = set()
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        local_ip = s.getsockname()[0]
        s.close()
        if not local_ip.startswith("127.") and not local_ip.startswith("169.254."):
            subnets.add(".".join(local_ip.split(".")[:3]))
    except Exception:
        pass

    try:
        for ip in socket.gethostbyname_ex(socket.gethostname())[2]:
            if not ip.startswith("127.") and not ip.startswith("169.254."):
                subnets.add(".".join(ip.split(".")[:3]))
    except Exception:
        pass

    return sorted(list(subnets))


def scan_subnet_for_port(subnet_prefix: str, port: int = 8088, timeout_s: float = 0.25) -> list[str]:
    """Scan all 254 hosts in a /24 subnet for open TCP port."""
    def check_ip(ip: str) -> str | None:
        if check_tcp_port(ip, port, timeout_s):
            return ip
        return None

    ips = [f"{subnet_prefix}.{i}" for i in range(1, 255)]
    found: list[str] = []
    with ThreadPoolExecutor(max_workers=64) as executor:
        futures = [executor.submit(check_ip, ip) for ip in ips]
        for f in as_completed(futures):
            res = f.result()
            if res:
                found.append(res)
    return found


def find_hub_lan_ip(preferred_ip: str | None = None, port: int = 8088) -> str | None:
    """Verify preferred_ip or scan local subnets for Hub on port 8088."""
    if preferred_ip and check_tcp_port(preferred_ip, port, timeout_s=1.5):
        return preferred_ip

    subnets = get_local_subnets()
    print(f"[*] Scanning local subnet(s) {subnets} for Hub on port {port}...")
    for sub in subnets:
        found = scan_subnet_for_port(sub, port)
        if found:
            return found[0]
    return None


def wait_for_ssh(ip: str, port: int = 22, timeout_s: int = 60) -> bool:
    """Check if SSH port is reachable."""
    t_end = time.time() + timeout_s
    while time.time() < t_end:
        if check_tcp_port(ip, port, timeout_s=1.0):
            return True
        time.sleep(1.0)
        print(".", end="", flush=True)
    return False


