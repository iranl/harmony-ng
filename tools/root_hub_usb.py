#!/usr/bin/env python3
"""Logitech Harmony Hub USB Root & Persistence Tool.

Permanently roots a stock or factory-reset Logitech Harmony Hub over USB HID:
- Installs MIPS Dropbear multi-call SSH server to /data/dropbearmulti
- Configures authorized_keys with your SSH public key
- Enables TDE gate (/etc/tdeenable) so Dropbear starts on every boot
- Disables hardware watchdog (/etc/nowatchdog)
- Optionally provisions Wi-Fi over USB HID

Requires NO Logitech cloud, NO Harmony app, NO XMPP, and NO hub_id.

Usage:
    python tools/root_hub_usb.py
    python tools/root_hub_usb.py --wifi-ssid "MyNetwork" --wifi-pass "Secret123"
    python tools/root_hub_usb.py --hub-ip 192.168.1.50
"""

from __future__ import annotations

import argparse
import hashlib
import os
import pathlib
import socket
import subprocess
import sys
import time

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
REPO_DIR = SCRIPT_DIR.parent
BIN_DIR = SCRIPT_DIR / "bin"
DROPBEAR_MIPS_PATH = BIN_DIR / "dropbearmulti_mips"

if str(REPO_DIR) not in sys.path:
    sys.path.insert(0, str(REPO_DIR))

from tools.harmony_hid import HarmonyHid, HUB_PID


BOOTSTRAP_SCRIPT_TEMPLATE = b"""#!/bin/sh
# Auto-generated by Harmony Hub Control USB Root Tool
# Phase 1: Install SSH authorized keys
mkdir -p /etc/dropbear /root/.ssh /home/root/.ssh
cat <<'EOF' > /etc/dropbear/authorized_keys
%PUBKEY%
EOF
cp /etc/dropbear/authorized_keys /root/.ssh/authorized_keys
cp /etc/dropbear/authorized_keys /home/root/.ssh/authorized_keys
chmod 700 /root /root/.ssh /home/root /home/root/.ssh
chmod 600 /etc/dropbear/authorized_keys /root/.ssh/authorized_keys /home/root/.ssh/authorized_keys

# Phase 2: Set blank root password fallback in /etc/passwd
sed -i 's/^root:[^:]*:/root::/' /etc/passwd

# Phase 3: Disable hardware watchdog
touch /etc/nowatchdog
chmod 644 /etc/nowatchdog

# Phase 4: Extract Dropbear multi-call binary using stock Lua
/usr/bin/lua -e 'local f=io.open("/usr/sbin/dropbearmulti","rb") f:seek("set",%OFFSET%) local g=io.open("/data/dropbearmulti","wb") while true do local b=f:read(65536) if not b then break end g:write(b) end f:close() g:close()'

chmod 755 /data/dropbearmulti
ln -sf /data/dropbearmulti /usr/sbin/dropbear
ln -sf /data/dropbearmulti /usr/sbin/dropbearkey
ln -sf /data/dropbearmulti /usr/sbin/dbclient
ln -sf /data/dropbearmulti /usr/sbin/scp

# Phase 5: Ensure RSA host key exists
if [ ! -r /etc/dropbear/dropbear_rsa_host_key ]; then
    /data/dropbearmulti dropbearkey -t rsa -f /etc/dropbear/dropbear_rsa_host_key
fi

# Phase 6: Start Dropbear SSH daemon
exec /data/dropbearmulti dropbear -R -p 0.0.0.0:22 "$@"
"""


def resolve_ssh_key(pubkey_path: str | None = None) -> tuple[pathlib.Path, str]:
    """Find existing harmony_owner key or generate a new ED25519 keypair."""
    ssh_dir = pathlib.Path.home() / ".ssh"
    ssh_dir.mkdir(parents=True, exist_ok=True)

    if pubkey_path:
        p = pathlib.Path(pubkey_path)
        if not p.is_file():
            raise FileNotFoundError(f"Specified pubkey not found: {pubkey_path}")
        return p, p.read_text(encoding="utf-8").strip()

    # Look for existing harmony_owner keys
    existing_keys = sorted(
        [k for k in ssh_dir.glob("harmony_owner_*.pub") if k.is_file()],
        key=lambda k: k.stat().st_mtime,
        reverse=True,
    )
    if existing_keys:
        chosen = existing_keys[0]
        print(f"[*] Using existing SSH key: {chosen}")
        return chosen, chosen.read_text(encoding="utf-8").strip()

    # Generate new ED25519 key
    new_priv = ssh_dir / "harmony_owner_ed25519"
    new_pub = ssh_dir / "harmony_owner_ed25519.pub"
    print(f"[*] Generating new SSH keypair: {new_priv}...")
    cmd = ["ssh-keygen", "-t", "ed25519", "-f", str(new_priv), "-N", "", "-C", "harmony-hub-owner"]
    subprocess.run(cmd, check=True)
    return new_pub, new_pub.read_text(encoding="utf-8").strip()


def find_dropbear_binary() -> pathlib.Path:
    candidates = [
        SCRIPT_DIR / "bin" / "dropbearmulti_mips",
        SCRIPT_DIR / "bin" / "dropbearmulti",
        REPO_DIR / "bin" / "dropbearmulti",
        REPO_DIR / "bin" / "dropbearmulti_mips",
        REPO_DIR / "payload" / "bin" / "dropbearmulti",
        REPO_DIR / "payload" / "bin" / "dropbearmulti_mips",
        SCRIPT_DIR / "dropbearmulti_mips",
        SCRIPT_DIR / "dropbearmulti",
    ]
    for c in candidates:
        if c.is_file():
            return c
    raise FileNotFoundError(f"MIPS Dropbear binary missing. Checked: {[str(c) for c in candidates]}")


def build_payload(pubkey_str: str) -> bytes:
    """Build self-extracting bootstrap script + MIPS Dropbear binary."""
    dropbear_path = find_dropbear_binary()
    mips_binary = dropbear_path.read_bytes()

    # Template offset placeholder format
    dummy_offset = b"00000000"
    base_script = BOOTSTRAP_SCRIPT_TEMPLATE.replace(b"%PUBKEY%", pubkey_str.strip().encode("ascii"))
    template = base_script.replace(b"%OFFSET%", dummy_offset)
    actual_offset = len(template)

    final_offset_str = f"{actual_offset:08d}".encode("ascii")
    script = base_script.replace(b"%OFFSET%", final_offset_str)
    assert len(script) == actual_offset, f"Script length mismatch: {len(script)} vs {actual_offset}"

    return script + mips_binary


def wait_for_ssh(ip: str, port: int = 22, timeout_s: int = 60) -> bool:
    """Check if SSH port is reachable."""
    t_end = time.time() + timeout_s
    while time.time() < t_end:
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.settimeout(1.0)
        try:
            s.connect((ip, port))
            s.close()
            return True
        except Exception:
            pass
        time.sleep(1.0)
        print(".", end="", flush=True)
    return False


def main() -> None:
    parser = argparse.ArgumentParser(description="Logitech Harmony Hub USB Root & Persistence Tool")
    parser.add_argument("--pubkey", help="Path to SSH public key to authorize")
    parser.add_argument("--wifi-ssid", help="Wi-Fi SSID to provision over USB")
    parser.add_argument("--wifi-pass", default="", help="Wi-Fi password to provision over USB")
    parser.add_argument("--wifi-enc", default="WPA2-PSK", help="Wi-Fi encryption (default: WPA2-PSK)")
    parser.add_argument("--wifi-only", action="store_true", help="Only configure Wi-Fi and reboot without restaging Dropbear")
    parser.add_argument("--hub-ip", help="Known Hub LAN IP address to verify SSH after reboot")
    parser.add_argument("--no-reboot", action="store_true", help="Do not reboot Hub after staging Dropbear")
    args = parser.parse_args()

    print("=" * 70)
    print(" LOGITECH HARMONY HUB USB ROOT & PERSISTENCE TOOL")
    print("=" * 70)

    # 1. Connect to Hub over USB HID
    print(f"[*] Searching for Harmony Hub over USB HID (046D:C129)...")
    hid = HarmonyHid(pid=HUB_PID)
    if not hid.open():
        print("[-] Error: Harmony Hub not detected on USB.")
        print("    Ensure the Hub is connected via micro-USB and powered ON.")
        sys.exit(1)

    try:
        # 2. Wi-Fi Provisioning
        if args.wifi_ssid:
            print(f"[*] Provisioning Wi-Fi SSID '{args.wifi_ssid}' over USB HID...")
            if hid.provision_wifi(args.wifi_ssid, args.wifi_pass, args.wifi_enc):
                print("[+] Wi-Fi credentials accepted by Hub.")
            else:
                print("[-] Warning: Wi-Fi provisioning command failed.")

        if args.wifi_only:
            if not args.no_reboot:
                print("[*] Sending reboot command to /sys/reboot...")
                try:
                    hid.reboot()
                    print("[+] Hub is rebooting to connect to Wi-Fi!")
                except Exception:
                    pass
                if args.hub_ip:
                    print(f"[*] Waiting for Dropbear SSH on {args.hub_ip}:22...")
                    if wait_for_ssh(args.hub_ip, 22, timeout_s=60):
                        print(f"\n[+] SUCCESS: Dropbear SSH is ONLINE at {args.hub_ip}:22!")
                    else:
                        print(f"\n[-] Timed out waiting for SSH on {args.hub_ip}.")
                else:
                    print("\n[+] Wi-Fi configuration complete! Hub is joining your network.")
            return

        # 3. Resolve SSH Public Key & Build Self-Extracting Payload
        pub_path, pub_str = resolve_ssh_key(args.pubkey)
        print(f"[+] Authorized public key: {pub_str.split()[0]} {pub_str.split()[-1]}")

        print(f"[*] Building self-extracting Dropbear payload (MIPS 24Kc)...")
        payload = build_payload(pub_str)
        print(f"[+] Payload built: {len(payload):,} bytes (MD5: {hashlib.md5(payload).hexdigest()})")

        # 5. Upload Dropbear Payload to /sys/dropbear
        print(f"[*] Staging Dropbear payload to /sys/dropbear ({len(payload):,} bytes)...")
        t0 = time.time()

        def progress(sent: int, total: int) -> None:
            pct = int(sent / total * 100)
            print(f"\r    Uploaded {sent:,} / {total:,} bytes ({pct}%)", end="", flush=True)

        hid.write_full_file("/sys/dropbear", payload, packets_per_chunk=5, progress_callback=progress)
        print(f"\n[+] Dropbear staging complete in {time.time() - t0:.1f}s.")

        # 6. Enable TDE Gate (/etc/tdeenable)
        print("[*] Arming boot trigger (/tde/enable -> /etc/tdeenable)...")
        if hid.set_tde_enable(True):
            print("[+] SUCCESS: /etc/tdeenable created on persistent overlay.")
        else:
            print("[-] Warning: Failed to confirm /tde/enable.")

        # 7. Reboot
        if not args.no_reboot:
            print("[*] Sending reboot command to /sys/reboot...")
            try:
                hid.reboot()
                print("[+] Hub is rebooting into rooted firmware multi-user mode!")
            except Exception:
                pass

            if args.hub_ip:
                print(f"[*] Waiting for Dropbear SSH on {args.hub_ip}:22...")
                if wait_for_ssh(args.hub_ip, 22, timeout_s=60):
                    print(f"\n[+] SUCCESS: Dropbear SSH is ONLINE at {args.hub_ip}:22!")
                    print(f"    Connect: ssh -i {pub_path.with_suffix('')} root@{args.hub_ip}")
                else:
                    print(f"\n[-] Timed out waiting for SSH on {args.hub_ip}.")
            else:
                print("\n[+] Setup complete! Dropbear SSH will start on port 22 on your LAN IP.")
        else:
            print("[+] Setup complete (reboot deferred).")

    finally:
        hid.close()


if __name__ == "__main__":
    main()
