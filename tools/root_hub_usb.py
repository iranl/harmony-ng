def backup_stock_partitions(hub_ip: str, priv_key_path: pathlib.Path) -> pathlib.Path | None:
    """Auto backup entire /cache and /data partitions over SSH to local backups/ directory."""
    print("\n[*] Starting automated stock backup of entire /cache and /data partitions...")
    backup_dir = REPO_DIR / "backups"
    backup_dir.mkdir(parents=True, exist_ok=True)

    timestamp = time.strftime("%Y%m%d_%H%M%S")
    backup_path = backup_dir / f"stock_hub_backup_{timestamp}.tar"
    latest_path = backup_dir / "stock_hub_backup_latest.tar"
    golden_path = backup_dir / "golden_hub_backup.tar"

    ssh_opts = [
        "-o", "StrictHostKeyChecking=no",
        "-o", "UserKnownHostsFile=NUL" if sys.platform == "win32" else "/dev/null",
        "-o", "LogLevel=ERROR",
        "-o", "ConnectTimeout=10",
    ]
    if priv_key_path.is_file():
        ssh_opts.extend(["-i", str(priv_key_path)])

    target = f"root@{hub_ip}"

    # Determine busybox command on Hub (check if /cache/bin/busybox or /data/codex/bin/busybox exists)
    chk_cmd = ["ssh"] + ssh_opts + [
        target,
        "if [ -x /cache/bin/busybox ]; then echo /cache/bin/busybox; elif [ -x /data/codex/bin/busybox ]; then echo /data/codex/bin/busybox; elif [ -x /tmp/busybox ]; then echo /tmp/busybox; else echo ''; fi",
    ]
    res = subprocess.run(chk_cmd, capture_output=True, text=True)
    bb_bin = res.stdout.strip()
    uploaded_temp_bb = False

    if not bb_bin:
        local_bb = find_busybox_binary()
        if not local_bb:
            print("[-] Error: BusyBox binary with tar support not found locally. Cannot take stock backup.")
            return None
        print(f"[*] Staging temporary BusyBox ({local_bb.stat().st_size:,} bytes) to Hub /tmp/busybox...")
        try:
            with open(local_bb, "rb") as f_in:
                subprocess.run(
                    ["ssh"] + ssh_opts + [target, "cat > /tmp/busybox && chmod 755 /tmp/busybox"],
                    input=f_in.read(),
                    check=True,
                    timeout=30,
                )
            bb_bin = "/tmp/busybox"
            uploaded_temp_bb = True
            print("[+] Staged /tmp/busybox successfully.")
        except Exception as e:
            print(f"[-] Failed to stage BusyBox on Hub: {e}")
            return None

    # Stream tarball from Hub (plain tar, no gzip)
    print(f"[*] Streaming entire /cache and /data partitions to {backup_path.name}...")
    tar_cmd = f"{bb_bin} tar -cf - /cache /data 2>/dev/null"
    try:
        t0 = time.time()
        with open(backup_path, "wb") as f_out:
            proc = subprocess.Popen(
                ["ssh"] + ssh_opts + [target, tar_cmd],
                stdout=f_out,
                stderr=subprocess.PIPE,
            )
            proc.wait(timeout=180)
            if proc.returncode not in (0, 1):
                print(f"[-] Tar process exited with code {proc.returncode}")

        if not backup_path.is_file() or backup_path.stat().st_size < 1000:
            print(f"[-] Backup file is empty or corrupted ({backup_path.stat().st_size if backup_path.is_file() else 0} bytes).")
            backup_path.unlink(missing_ok=True)
            return None

        with tarfile.open(backup_path, "r:*") as tar:
            members = tar.getnames()

        elapsed = time.time() - t0
        size_mb = backup_path.stat().st_size / (1024 * 1024)
        print(f"[+] Stock backup verified successfully! ({size_mb:.2f} MB, {len(members)} entries in {elapsed:.1f}s)")
        print(f"    Saved to: {backup_path}")

        # Update latest and golden
        shutil.copyfile(backup_path, latest_path)
        print(f"    Updated: {latest_path.name}")
        if not golden_path.is_file():
            shutil.copyfile(backup_path, golden_path)
            print(f"    Created golden baseline: {golden_path.name}")

    except Exception as e:
        print(f"[-] Stock backup failed: {e}")
        backup_path.unlink(missing_ok=True)
        return None
    finally:
        if uploaded_temp_bb:
            subprocess.run(["ssh"] + ssh_opts + [target, "rm -f /tmp/busybox"], capture_output=True)

    return backup_path


def main() -> None:
    parser = argparse.ArgumentParser(description="Logitech Harmony Hub USB Root & Persistence Tool")
    parser.add_argument("--pubkey", help="Path to SSH public key to authorize")
    parser.add_argument("--wifi-ssid", help="Wi-Fi SSID to provision over USB")
    parser.add_argument("--wifi-pass", default=None, help="Wi-Fi password (prompted if omitted)")
    parser.add_argument("--wifi-enc", default="WPA2-PSK", help="Wi-Fi encryption (default: WPA2-PSK)")
    parser.add_argument("--wifi-only", action="store_true", help="Only configure Wi-Fi and reboot without restaging Dropbear")
    parser.add_argument("--hub-ip", help="Known Hub LAN IP address to verify SSH after reboot")
    parser.add_argument("--no-reboot", action="store_true", help="Do not reboot Hub after staging Dropbear")
    parser.add_argument("--no-backup", action="store_true", help="Skip automatic stock backup on gaining root")
    parser.add_argument("--skip-fw-check", action="store_true", help="Skip firmware version check and upgrade prompt")
    args = parser.parse_args()

    print("=" * 70)
    print(" LOGITECH HARMONY HUB USB ROOT & PERSISTENCE TOOL")
    print("=" * 70)

    # 1. Connect to Hub over USB HID
    print("[*] Searching for Harmony Hub over USB HID (046D:C129 / 046D:C132)...")
    hid = None
    connected_pid = None
    for pid in ALL_HUB_PIDS:
        candidate = HarmonyHid(pid=pid)
        if candidate.open():
            hid = candidate
            connected_pid = pid
            break

    if not hid or not connected_pid:
        print("[-] Error: Harmony Hub not detected on USB.")
        print("    Ensure the Hub is connected via micro-USB and powered ON.")
        sys.exit(1)

    dev_label = "Harmony Pro Hub (2400)" if connected_pid == HUB_PRO_PID else "Harmony Hub"
    print(f"[+] Connected to {dev_label} (USB {connected_pid:04X})")

    try:
        # Check firmware version
        if not args.skip_fw_check:
            sysinfo = hid.get_sysinfo()
            current_fw = sysinfo.get("fw_ver") or sysinfo.get("version") or sysinfo.get("fw_version")
            target_skin = 115 if connected_pid == HUB_PRO_PID else DEFAULT_HUB_SKIN
            if sysinfo.get("skin"):
                try:
                    target_skin = int(sysinfo["skin"])
                except ValueError:
                    pass
            if current_fw:
                print(f"[*] Hub reports firmware version: {current_fw} (Skin {target_skin})")
                try:
                    from tools.harmony_firmware import (
                        query_latest_firmware,
                        DEFAULT_HUB_SKIN,
                        download_file,
                        parse_hfw2_bundle,
                        flash_firmware,
                    )
                    res = query_latest_firmware(target_skin)
                    if res and res.get("Id"):
                        latest_fw = res["Id"]
                        if current_fw != latest_fw:
                            print(f"\n[!] Hub firmware is {current_fw}, but latest official firmware is {latest_fw}.")
                            ans = input(f"[?] Download and install latest official firmware ({latest_fw}) first? (y/N): ")
                            if ans.strip().lower() == "y":
                                fw_dir = REPO_DIR / "firmware"
                                fw_file = fw_dir / f"hub_{target_skin}_{latest_fw}.hfw2"
                                if not fw_file.is_file():
                                    if not download_file(res["URI"], fw_file, progress_desc=f"Downloading {fw_file.name}"):
                                        print("[-] Firmware download failed. Proceeding with current firmware...")
                                if fw_file.is_file():
                                    bundle = parse_hfw2_bundle(fw_file)
                                    print("[*] Installing latest firmware over USB HID...")
                                    hid.close()
                                    if flash_firmware(bundle, target_device="hub", skip_confirm=True):
                                        print("[*] Waiting 30s for Hub to complete reboot and flash...")
                                        time.sleep(15)
                                        t_reconnect = time.time() + 60
                                        while time.time() < t_reconnect:
                                            for p in ALL_HUB_PIDS:
                                                h_test = HarmonyHid(pid=p)
                                                if h_test.open():
                                                    hid = h_test
                                                    connected_pid = p
                                                    print(f"\n[+] Hub re-enumerated on USB (PID {p:04X}) after firmware upgrade!")
                                                    break
                                            if hid and hid.dev:
                                                break
                                            time.sleep(2)
                                            print(".", end="", flush=True)
                                        else:
                                            print("\n[-] Timed out waiting for Hub to re-enumerate on USB after upgrade.")
                                            sys.exit(1)
                        else:
                            print(f"[+] Hub is running the latest official firmware ({latest_fw}).")
                except Exception as e:
                    print(f"[-] Firmware version check failed ({e}), continuing...")

        # 2. Check Wi-Fi Connection Status over USB HID
        print("[*] Checking Hub Wi-Fi connection over USB HID...")
        wifi_status = hid.get_wifi_status()
        conn_status = wifi_status.get("connect_status", "").lower()
        hub_ip = wifi_status.get("ip_address", "").strip()
        ssid = wifi_status.get("ssid", "").strip()

        is_connected = conn_status == "connected" and hub_ip and hub_ip != "0.0.0.0"

        # Force Wi-Fi setup if disconnected or if explicit SSID passed
        if not is_connected or args.wifi_ssid:
            if not is_connected:
                print(f"[-] Hub is NOT connected to Wi-Fi (status: '{conn_status or 'disconnected'}').")
                print("    [!] A verified Wi-Fi connection to your network is REQUIRED before rooting.")
                print("        This prevents lockout by ensuring the Hub is reachable over SSH.")

            target_ssid = args.wifi_ssid
            if not target_ssid:
                target_ssid = input("\nEnter Wi-Fi SSID (2.4 GHz): ").strip()
                while not target_ssid:
                    target_ssid = input("SSID cannot be empty. Enter Wi-Fi SSID: ").strip()

            target_pass = args.wifi_pass
            if target_pass is None and args.wifi_enc.upper() not in ("NONE", "OPEN"):
                import getpass
                print("Note: If password contains special characters (like $), interactive prompt preserves them literally.")
                target_pass = getpass.getpass(f"Enter Wi-Fi password for '{target_ssid}': ")

            print(f"[*] Provisioning Wi-Fi SSID '{target_ssid}' over USB HID...")
            if not hid.provision_wifi(target_ssid, target_pass or "", args.wifi_enc):
                print("[-] Error: Failed to send Wi-Fi credentials over USB HID.")
                sys.exit(1)

            print("[+] Wi-Fi credentials accepted by Hub.")
            print(f"[*] Waiting for Hub to connect to '{target_ssid}' (up to 40s)...")
            t_deadline = time.time() + 40
            is_connected = False
            while time.time() < t_deadline:
                time.sleep(2)
                wifi_status = hid.get_wifi_status()
                conn_status = wifi_status.get("connect_status", "").lower()
                hub_ip = wifi_status.get("ip_address", "").strip()
                ssid = wifi_status.get("ssid", "").strip()
                if conn_status == "connected" and hub_ip and hub_ip != "0.0.0.0":
                    is_connected = True
                    print(f"\n[+] Wi-Fi connected! SSID='{ssid}', IP={hub_ip}")
                    break
                print(".", end="", flush=True)

            if not is_connected:
                print(f"\n[-] ERROR: Hub failed to connect to Wi-Fi within 40s (status: '{conn_status}').")
                print("[-] ROOTING ABORTED: Will NOT install Dropbear or arm boot trigger without Wi-Fi.")
                sys.exit(1)
        else:
            print(f"[+] Wi-Fi already connected: SSID='{ssid}', IP={hub_ip}")

        # 3. LAN Reachability & Port 8088 Scan
        print(f"[*] Verifying LAN reachability on {hub_ip}...")
        lan_ip = None
        if check_tcp_port(hub_ip, 8088, timeout_s=2.0):
            print(f"[+] Hub verified on LAN at {hub_ip}:8088 (stock Luaworks active).")
            lan_ip = hub_ip
        elif check_tcp_port(hub_ip, 22, timeout_s=2.0):
            print(f"[+] Hub verified on LAN at {hub_ip}:22 (Dropbear SSH active).")
            lan_ip = hub_ip
        else:
            print(f"[*] Direct probe to {hub_ip} did not respond. Scanning local network for port 8088...")
            discovered = find_hub_lan_ip(preferred_ip=args.hub_ip or hub_ip, port=8088)
            if not discovered:
                discovered = find_hub_lan_ip(preferred_ip=args.hub_ip or hub_ip, port=22)
            if discovered:
                print(f"[+] Discovered Hub on LAN at {discovered}!")
                lan_ip = discovered
            else:
                print(f"[-] ERROR: Hub Wi-Fi reports IP {hub_ip}, but Hub is NOT reachable from this PC on the local network.")
                print("    Ensure this PC and the Hub are on the same Wi-Fi network/subnet and AP isolation is OFF.")
                print("[-] ROOTING ABORTED: Will NOT install Dropbear or arm boot trigger without verified LAN reachability.")
                sys.exit(1)

        if args.wifi_only:
            if not args.no_reboot:
                print("[*] Sending reboot command to /sys/reboot...")
                try:
                    hid.reboot()
                    print("[+] Hub is rebooting to finalize Wi-Fi!")
                except Exception:
                    pass
                print(f"\n[+] Wi-Fi configuration complete! Hub IP: {lan_ip}")
            return

        # 4. Resolve SSH Public Key & Build Self-Extracting Payload
        pub_path, pub_str = resolve_ssh_key(args.pubkey)
        print(f"[+] Authorized public key: {pub_str.split()[0]} {pub_str.split()[-1]}")

        print(f"[*] Building self-extracting Dropbear payload (MIPS 24Kc)...")
        payload = build_payload(pub_str)
        print(f"[+] Payload built: {len(payload):,} bytes (MD5: {hashlib.md5(payload).hexdigest()})")

        # 5. Upload Dropbear Payload to /sys/dropbear
        print(f"[*] Staging Dropbear payload to /sys/dropbear ({len(payload):,} bytes)...")
        t0 = time.time()

        def progress(sent: int, total: int) -> None:
            pct = int(sent / total * 100)
            print(f"\r    Uploaded {sent:,} / {total:,} bytes ({pct}%)", end="", flush=True)

        hid.write_full_file("/sys/dropbear", payload, packets_per_chunk=5, progress_callback=progress)
        print(f"\n[+] Dropbear staging complete in {time.time() - t0:.1f}s.")

        # 6. Enable TDE Gate (/etc/tdeenable)
        print("[*] Arming boot trigger (/tde/enable -> /etc/tdeenable)...")
        if hid.set_tde_enable(True):
            print("[+] SUCCESS: /etc/tdeenable created on persistent overlay.")
        else:
            print("[-] Warning: Failed to confirm /tde/enable.")

        # 7. Reboot
        if not args.no_reboot:
            print("[*] Sending reboot command to /sys/reboot...")
            try:
                hid.reboot()
                print("[+] Hub is rebooting into rooted firmware multi-user mode!")
            except Exception:
                pass

            target_verify_ip = lan_ip or args.hub_ip or hub_ip
            if target_verify_ip:
                print(f"[*] Waiting for Dropbear SSH on {target_verify_ip}:22...")
                if wait_for_ssh(target_verify_ip, 22, timeout_s=60):
                    print(f"\n[+] SUCCESS: Dropbear SSH is ONLINE at {target_verify_ip}:22!")
                    priv_key_file = pub_path.with_suffix('')
                    print(f"    Connect: ssh -i {priv_key_file} root@{target_verify_ip}")
                    if not args.no_backup:
                        backup_stock_partitions(target_verify_ip, priv_key_file)
                else:
                    print(f"\n[-] Timed out waiting for SSH on {target_verify_ip}.")
            else:
                print("\n[+] Setup complete! Dropbear SSH will start on port 22 on your LAN IP.")
        else:
            print("[+] Setup complete (reboot deferred).")

    finally:
        hid.close()


