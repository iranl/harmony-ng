BOOTSTRAP_SCRIPT_TEMPLATE = b"""#!/bin/sh
# Auto-generated by Harmony Hub Control USB Root Tool
# USB id 046D:C132 is also listed for a Harmony remote: change nothing on an ARM remote
case "$(uname -m 2>/dev/null)" in arm*) exit 0 ;; esac

# Phase 1: Install SSH authorized keys
mkdir -p /etc/dropbear /root/.ssh /home/root/.ssh
cat <<'EOF' > /etc/dropbear/authorized_keys
%PUBKEY%
EOF
cp /etc/dropbear/authorized_keys /root/.ssh/authorized_keys
cp /etc/dropbear/authorized_keys /home/root/.ssh/authorized_keys
chmod 700 /root /root/.ssh /home/root /home/root/.ssh
chmod 600 /etc/dropbear/authorized_keys /root/.ssh/authorized_keys /home/root/.ssh/authorized_keys

# Phase 2: Set blank root password fallback in /etc/passwd (serial console only: SSH takes keys)
sed -i 's/^root:[^:]*:/root::/' /etc/passwd

# Phase 3: Disable hardware watchdog
touch /etc/nowatchdog
chmod 644 /etc/nowatchdog

# Phase 4: Extract Dropbear multi-call binary using stock Lua
/usr/bin/lua -e 'local f=io.open("/usr/sbin/dropbearmulti","rb") f:seek("set",%OFFSET%) local g=io.open("/data/dropbearmulti","wb") while true do local b=f:read(65536) if not b then break end g:write(b) end f:close() g:close()'

chmod 755 /data/dropbearmulti
# /usr/sbin/dropbear (started by the stock boot script) takes keys only: -s refuses password
# logins, -g also for root. Written under a new name and renamed: this script may be running
# from that path.
cat <<'EOF' > /usr/sbin/dropbear.new
#!/bin/sh
exec /data/dropbearmulti dropbear -s -g "$@"
EOF
chmod 755 /usr/sbin/dropbear.new
mv -f /usr/sbin/dropbear.new /usr/sbin/dropbear
ln -sf /data/dropbearmulti /usr/sbin/dropbearkey
ln -sf /data/dropbearmulti /usr/sbin/scp

# Phase 5: Ensure the Ed25519 host key exists (the only host key type the server loads)
if [ ! -r /etc/dropbear/dropbear_ed25519_host_key ]; then
    /data/dropbearmulti dropbearkey -t ed25519 -f /etc/dropbear/dropbear_ed25519_host_key
fi

# Phase 6: Start Dropbear SSH daemon in background and let rcS continue (key logins only)
/data/dropbearmulti dropbear -s -g -R -p 0.0.0.0:22 "$@"
exit 0
"""


WIFI_PASS_ENV = "HARMONY_WIFI_PASS"


def wifi_password(args, ssid: str) -> str | None:
    """The Wi-Fi password: --wifi-pass, else $HARMONY_WIFI_PASS, else a prompt (open networks:
    none). On the command line it lands in the shell history and the process list, so say so."""
    if args.wifi_pass is not None:
        print(f"[!] --wifi-pass puts the password in your shell history and the process list; "
              f"leave it out to be asked, or set {WIFI_PASS_ENV}.")
        return args.wifi_pass
    if os.environ.get(WIFI_PASS_ENV) is not None:
        return os.environ[WIFI_PASS_ENV]
    if args.wifi_enc.upper() in ("NONE", "OPEN"):
        return None
    import getpass
    print("Note: If password contains special characters (like $), interactive prompt preserves them literally.")
    return getpass.getpass(f"Enter Wi-Fi password for '{ssid}': ")


def parse_skin_id(value: object) -> int | None:
    """Skin id from the Hub's /sys/sysinfo: hex as the Hub reports it ("0x6A") or decimal ("106").

    None when it is missing or unreadable. A plain int() refused the hex form, so every Hub was
    checked as skin 97 (the Creemore Hub, skin 106, has its own firmware image).
    """
    text = str(value if value is not None else "").strip()
    try:
        return int(text, 16) if text.lower().startswith("0x") else int(text, 10)
    except ValueError:
        return None


def latest_firmware_for_skin(skin: int, default_skin: int, query) -> tuple[int, dict | None]:
    """Latest official firmware for the Hub's skin, else for the default Hub skin.

    Returns the skin the answer is for and the answer (None when neither has one). The flash step
    still refuses a bundle whose skin list does not include the Hub's skin.
    """
    res = query(skin, silent_on_empty=skin != default_skin)
    if (res and res.get("Id")) or skin == default_skin:
        return skin, res
    print(f"[*] No firmware listed for skin {skin}, checking skin {default_skin}...")
    return default_skin, query(default_skin)


def private_key_path(pub_path: pathlib.Path) -> pathlib.Path:
    """The private key that belongs to a public key file: the same name without ".pub", as
    ssh-keygen names them. (with_suffix("") is wrong for names such as "id.backup.pub" or
    "mykey.pub.txt".)"""
    if pub_path.name.endswith(".pub"):
        return pub_path.with_name(pub_path.name[:-4])
    raise ValueError(f"{pub_path} does not end in .pub: pass the public key that sits next to its private key")


def _ed25519_only(pub: pathlib.Path) -> str:
    """The key line of pub; the Hub's SSH server takes Ed25519 user keys only."""
    text = pub.read_text(encoding="utf-8").strip()
    if not text.startswith("ssh-ed25519 "):
        raise ValueError(f"{pub} is a {text.split(' ', 1)[0] or 'unknown'} key: the Hub's SSH server takes "
                         "Ed25519 keys only (ssh-keygen -t ed25519)")
    return text


def resolve_ssh_key(pubkey_path: str | None = None, authorize: bool = True) -> tuple[pathlib.Path, str]:
    """Find existing harmony_owner key or generate a new ED25519 keypair."""
    ssh_dir = pathlib.Path.home() / ".ssh"
    ssh_dir.mkdir(parents=True, exist_ok=True)

    if pubkey_path:
        p = pathlib.Path(pubkey_path)
        if not p.is_file():
            raise FileNotFoundError(f"Specified pubkey not found: {pubkey_path}")
        return p, _ed25519_only(p) if authorize else p.read_text(encoding="utf-8").strip()

    # Look for existing harmony_owner keys
    existing_keys = sorted(
        [k for k in ssh_dir.glob("harmony_owner_*.pub") if k.is_file()],
        key=lambda k: k.stat().st_mtime,
        reverse=True,
    )
    # the newest Ed25519 one, also without authorize (restore_stock.py --skip-usb-root logs in to a
    # Hub whose server takes Ed25519 keys only): an RSA key next to it must not be picked
    ed = [k for k in existing_keys if k.read_text(encoding="utf-8").startswith("ssh-ed25519 ")]
    existing_keys = ed or existing_keys
    if existing_keys:
        chosen = existing_keys[0]
        print(f"[*] Using existing SSH key: {chosen}")
        return chosen, _ed25519_only(chosen) if authorize else chosen.read_text(encoding="utf-8").strip()

    # Generate new ED25519 key
    new_priv = ssh_dir / "harmony_owner_ed25519"
    new_pub = ssh_dir / "harmony_owner_ed25519.pub"
    print(f"[*] Generating new SSH keypair: {new_priv}...")
    cmd = ["ssh-keygen", "-t", "ed25519", "-f", str(new_priv), "-N", "", "-C", "harmony-hub-owner"]
    subprocess.run(cmd, check=True)
    return new_pub, new_pub.read_text(encoding="utf-8").strip()


