#!/usr/bin/env python3
"""
update_ca_bundle.py - Curated Root CA Bundle Updater for Harmony Hub

Generates and updates a space-efficient, curated CA certificate bundle (payload/config/cacert.pem)
based on ESP-IDF's common certificate authorities (cmn_crt_authorities.csv) and Mozilla's
root store (cacrt_all.pem).

References:
  https://github.com/espressif/esp-idf/tree/master/components/mbedtls/esp_crt_bundle
"""

import os
import sys
import re
import csv
import ssl
import argparse
import urllib.request
import urllib.error
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

DEFAULT_CSV_URL = (
    "https://raw.githubusercontent.com/espressif/esp-idf/master/components/mbedtls/esp_crt_bundle/cmn_crt_authorities.csv"
)
DEFAULT_ALL_URL = (
    "https://raw.githubusercontent.com/espressif/esp-idf/master/components/mbedtls/esp_crt_bundle/cacrt_all.pem"
)
DEFAULT_LOCAL_CSV = REPO_ROOT / "payload" / "config" / "cmn_crt_authorities.csv"
DEFAULT_OUTPUT = REPO_ROOT / "payload" / "config" / "cacert.pem"

USER_AGENT = "HarmonyHub-CABundleUpdater/1.0"


def fetch_source(source_path_or_url: str) -> str:
    """Read data from either a local file or HTTP/HTTPS URL."""
    if source_path_or_url.startswith("http://") or source_path_or_url.startswith("https://"):
        req = urllib.request.Request(source_path_or_url, headers={"User-Agent": USER_AGENT})
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return resp.read().decode("utf-8", errors="replace")
        except urllib.error.URLError as e:
            raise RuntimeError(f"Failed to fetch {source_path_or_url}: {e}") from e
    else:
        path = Path(source_path_or_url)
        if not path.is_file():
            raise FileNotFoundError(f"File not found: {path}")
        return path.read_text(encoding="utf-8", errors="replace")


def parse_authorities(csv_text: str) -> set[str]:
    """Parse common authority names from CSV content."""
    filter_set = set()
    reader = csv.reader(csv_text.splitlines())
    for row in reader:
        if row and len(row) > 1:
            name = row[1].strip()
            if name and name != "Common Name or Certificate Name":
                filter_set.add(name)
    return filter_set


def parse_certificates(all_pem_text: str, filter_set: set[str]) -> list[tuple[str, str]]:
    """
    Extract certificates matching the filter set.
    Returns list of (authority_name, normalized_pem_block) tuples.
    """
    # Pattern matching gen_crt_bundle.py in esp-idf
    pattern = re.compile(r"(^.+?)\n(=+\n[\s\S]+?END CERTIFICATE-----\n)", re.MULTILINE)
    matches = pattern.findall(all_pem_text)

    matched = []
    for name, block in matches:
        name_clean = name.strip()
        if name_clean in filter_set:
            pem_match = re.search(r"(-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----)", block)
            if pem_match:
                pem = pem_match.group(1).strip()
                # Ensure newline after BEGIN CERTIFICATE
                if not pem.startswith("-----BEGIN CERTIFICATE-----\n"):
                    pem = pem.replace("-----BEGIN CERTIFICATE-----", "-----BEGIN CERTIFICATE-----\n", 1)
                # Ensure newline before END CERTIFICATE
                if not pem.endswith("\n-----END CERTIFICATE-----"):
                    pem = pem.replace("-----END CERTIFICATE-----", "\n-----END CERTIFICATE-----")
                matched.append((name_clean, pem))

    # Sort deterministically by authority name
    matched.sort(key=lambda x: x[0])
    return matched


def build_bundle_text(matched_certs: list[tuple[str, str]]) -> str:
    """Format matching certificates into final cacert.pem text."""
    lines = [
        "## Curated CA Bundle based on ESP-IDF common authorities (cmn_crt_authorities.csv)",
        "## Source: https://github.com/espressif/esp-idf/tree/master/components/mbedtls/esp_crt_bundle",
        "## Auto-generated by scripts/update_ca_bundle.py - DO NOT EDIT MANUALLY",
        "##",
        "",
    ]
    for name, pem in matched_certs:
        lines.append(name)
        lines.append("================")
        lines.append(pem)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def validate_bundle(bundle_text: str) -> int:
    """Validate bundle with Python SSL context. Returns count of loaded CA certificates."""
    ctx = ssl.create_default_context()
    ctx.load_verify_locations(cadata=bundle_text)
    return len(ctx.get_ca_certs())


def set_github_output(name: str, value: str):
    """Write output parameter for GitHub Actions if GITHUB_OUTPUT is set."""
    output_path = os.environ.get("GITHUB_OUTPUT")
    if output_path and os.path.exists(output_path):
        with open(output_path, "a", encoding="utf-8") as f:
            f.write(f"{name}={value}\n")


def main():
    parser = argparse.ArgumentParser(
        description="Update curated CA bundle based on ESP-IDF common certificate authorities."
    )
    parser.add_argument(
        "--authorities-csv",
        default=DEFAULT_CSV_URL,
        help="URL or local path to cmn_crt_authorities.csv",
    )
    parser.add_argument(
        "--cacrt-all",
        default=DEFAULT_ALL_URL,
        help="URL or local path to cacrt_all.pem master bundle",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="Output path for curated cacert.pem",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check if current bundle is up-to-date without modifying (exit 1 if changed, 0 if up to date)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show diff and summary without modifying files",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="Suppress informational output",
    )

    args = parser.parse_args()

    # 1. Fetch authorities CSV (with local fallback if remote fails)
    try:
        csv_text = fetch_source(args.authorities_csv)
    except Exception as e:
        if DEFAULT_LOCAL_CSV.is_file():
            if not args.quiet:
                print(f"[!] Warning: Remote CSV fetch failed ({e}), falling back to {DEFAULT_LOCAL_CSV}")
            csv_text = DEFAULT_LOCAL_CSV.read_text(encoding="utf-8")
        else:
            raise

    filter_set = parse_authorities(csv_text)
    if not filter_set:
        print("[-] Error: Authority list is empty!", file=sys.stderr)
        sys.exit(2)

    # 2. Fetch master bundle
    all_pem_text = fetch_source(args.cacrt_all)

    # 3. Parse matching certificates
    matched = parse_certificates(all_pem_text, filter_set)
    if not matched:
        print("[-] Error: No matching certificates found in master bundle!", file=sys.stderr)
        sys.exit(2)

    new_bundle = build_bundle_text(matched)

    # 4. Validate bundle syntax & SSL loadability
    try:
        ca_cert_count = validate_bundle(new_bundle)
    except Exception as e:
        print(f"[-] Error: Generated bundle failed SSL validation: {e}", file=sys.stderr)
        sys.exit(3)

    # 5. Check against existing bundle
    current_bundle = ""
    if args.output.is_file():
        current_bundle = args.output.read_text(encoding="utf-8", errors="replace")

    # Normalize newlines for comparison
    is_identical = new_bundle.strip().replace("\r\n", "\n") == current_bundle.strip().replace("\r\n", "\n")

    if is_identical:
        if not args.quiet:
            print(f"[=] CA bundle {args.output.name} is already up to date ({len(matched)} authorities, {ca_cert_count} CAs).")
        set_github_output("changed", "false")
        set_github_output("cert_count", str(len(matched)))
        sys.exit(0)

    # Bundle has changed
    if not args.quiet:
        print(f"[*] Curated CA bundle has changes:")
        print(f"    Target:      {args.output}")
        print(f"    Authorities: {len(matched)} matching")
        print(f"    Certificates:{ca_cert_count} loaded into SSL context")
        print(f"    Size:        {len(current_bundle)} -> {len(new_bundle)} bytes")

    if args.check:
        print("[-] Check failed: Curated CA bundle is out of date.", file=sys.stderr)
        set_github_output("changed", "true")
        set_github_output("cert_count", str(len(matched)))
        sys.exit(1)

    if args.dry_run:
        print("[*] Dry run: No changes written.")
        set_github_output("changed", "true")
        set_github_output("cert_count", str(len(matched)))
        sys.exit(0)

    # Write changes
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(new_bundle, encoding="utf-8")
    if not args.quiet:
        print(f"[+] Successfully updated {args.output} ({len(matched)} authorities, {ca_cert_count} CAs).")

    set_github_output("changed", "true")
    set_github_output("cert_count", str(len(matched)))
    sys.exit(0)


if __name__ == "__main__":
    main()
